function fillTemplate(template, signId) {
  return template
    .replaceAll('{{id}}', String(signId))
    .replaceAll('{{step}}', String(signId))
}

function createSign(optionId, signId) {
  const config = signTemplates[optionId]
  const reading = config.readings[(signId - 1) % config.readings.length]
  const level = levelSequence[(signId - 1) % levelSequence.length]

  return {
    id: signId,
    label: `第${signId}签`,
    direction: config.direction,
    level,
    attribute: level === '中平' ? '一般的签' : '优质吉签',
    poem: fillTemplate(reading.poem, signId),
    summary: fillTemplate(reading.summary, signId),
    vision: config.vision,
  }
}

export const fortuneSignsByOption = Object.fromEntries(
  Object.keys(signTemplates).map((optionId) => [
    optionId,
    Array.from({ length: 100 }, (_, index) => createSign(optionId, index + 1)),
  ]),
)

